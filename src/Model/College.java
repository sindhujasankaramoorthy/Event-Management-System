package Model;

public class College {
    private int cId;
    private String cName;
    private String phNo;
    private String location;
    private String email;

    public College(int cId, String cName, String phNo, String location, String email) {
        this.cId = cId;
        this.cName = cName;
        this.phNo = phNo;
        this.location = location;
        this.email = email;
    }

}